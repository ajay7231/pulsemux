import asyncio
import logging
from typing import Dict, List, Optional, Set

logger = logging.getLogger(__name__)


class CancellationEngine:
    """
    Manages structured task cancellation and context reconciliation for barge-in interruptions.
    Ensures zero orphaned asyncio tasks and reconciles conversation history in Redis
    to accurately reflect only the words the caller actually heard before interrupting.
    """

    def __init__(self, ms_per_word: float = 380.0):
        # Average English conversational speaking rate is ~150 WPM (~380-400ms per word)
        self.ms_per_word = ms_per_word
        self._active_tasks: Dict[str, Set[asyncio.Task]] = {}
        self._turn_transcripts: Dict[str, str] = {}

    def register_task(self, turn_id: str, task: asyncio.Task) -> None:
        """Associates an active asyncio Task (LLM or TTS) with a turn ID."""
        if turn_id not in self._active_tasks:
            self._active_tasks[turn_id] = set()
        self._active_tasks[turn_id].add(task)
        task.add_done_callback(lambda t: self._cleanup_task(turn_id, t))

    def _cleanup_task(self, turn_id: str, task: asyncio.Task) -> None:
        if turn_id in self._active_tasks:
            self._active_tasks[turn_id].discard(task)
            if not self._active_tasks[turn_id]:
                del self._active_tasks[turn_id]

    def record_turn_text(self, turn_id: str, full_text: str) -> None:
        """Stores the planned full response text generated by the LLM for this turn."""
        self._turn_transcripts[turn_id] = full_text

    async def handle_interrupt(
        self,
        call_id: str,
        interrupted_turn_id: str,
        played_duration_ms: int,
    ) -> str:
        """
        Executes immediate cancellation of all in-flight tasks for the interrupted turn
        and reconciles the assistant message to match the exact spoken portion.
        Returns the truncated text string.
        """
        logger.info(
            f"[CancellationEngine] Call {call_id} interrupted turn {interrupted_turn_id}. "
            f"Played duration: {played_duration_ms}ms"
        )

        # 1. Cancel in-flight asyncio tasks immediately
        tasks = self._active_tasks.pop(interrupted_turn_id, set())
        for task in tasks:
            if not task.done():
                task.cancel()
        if tasks:
            logger.info(f"[CancellationEngine] Cancelled {len(tasks)} in-flight tasks for turn {interrupted_turn_id}")

        # 2. Context Truncation Reconciliation
        full_text = self._turn_transcripts.get(interrupted_turn_id, "")
        if not full_text:
            return ""

        words = full_text.split()
        if not words:
            return ""

        # Calculate estimated words spoken: played_duration_ms / ms_per_word
        spoken_word_count = int(played_duration_ms / self.ms_per_word)
        spoken_word_count = max(0, min(len(words), spoken_word_count))

        truncated_words = words[:spoken_word_count]
        reconciled_text = " ".join(truncated_words)
        if spoken_word_count < len(words):
            reconciled_text += " [interrupted]"

        logger.info(
            f"[CancellationEngine] Reconciled turn {interrupted_turn_id} "
            f"from '{full_text}' to '{reconciled_text}'"
        )

        return reconciled_text
